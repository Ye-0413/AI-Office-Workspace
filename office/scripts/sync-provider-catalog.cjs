#!/usr/bin/env node
'use strict';

// Build-time only: copy the authoritative upstream registry into a small runtime
// artifact. This script never invokes an installer or reads user AI settings.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');

const DEFAULT_REGISTRY_ROOT = path.resolve(__dirname, '../..');
const DEFAULT_OUTPUT = path.resolve(__dirname, '../lib/provider-catalog.json');
const sha = (value) => createHash('sha256').update(value).digest('hex');

function jsonValue(value, at = 'registry') {
  if (value === null || ['string', 'boolean'].includes(typeof value)) return value;
  if (typeof value === 'number' && Number.isFinite(value)) return value;
  if (Array.isArray(value)) return value.map((item, i) => jsonValue(item, `${at}[${i}]`));
  if (value && typeof value === 'object' && Object.getPrototypeOf(value) === Object.prototype) {
    const output = {};
    for (const [key, item] of Object.entries(value)) {
      if (item !== undefined) output[key] = jsonValue(item, `${at}.${key}`);
    }
    return output;
  }
  throw new Error(`Non-JSON provider metadata at ${at}`);
}

function buildCatalog({ registryRoot = DEFAULT_REGISTRY_ROOT } = {}) {
  // Node keys require.cache by real paths (macOS /var and /tmp are aliases).
  const sourceRoot = fs.realpathSync(path.resolve(registryRoot));
  const registryFile = path.join(sourceRoot, 'agents', 'registry.js');
  const agentsRoot = path.dirname(registryFile);
  if (!fs.existsSync(registryFile)) throw new Error(`Provider registry source not found: ${registryFile}`);
  // Refresh only this source tree so a check made after an upstream update
  // cannot accidentally compare against Node's previous module cache.
  for (const file of Object.keys(require.cache)) {
    if (file === registryFile || file.startsWith(agentsRoot + path.sep)) delete require.cache[file];
  }
  const registry = require(registryFile);
  if (!registry || typeof registry.getAllAgents !== 'function') throw new Error('Provider registry must export getAllAgents()');
  const raw = registry.getAllAgents();
  if (!Array.isArray(raw) || !raw.length) throw new Error('Provider registry is empty');
  const providers = raw.map((item, i) => jsonValue(item, `providers[${i}]`));
  const ids = new Set();
  for (const item of providers) {
    if (!item || typeof item.id !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(item.id) || ids.has(item.id)) throw new Error('Provider IDs must be unique canonical strings');
    if (typeof item.name !== 'string' || !item.name.trim()) throw new Error(`Provider ${item.id} has no display name`);
    if (!item.capabilities || typeof item.capabilities !== 'object' || Array.isArray(item.capabilities) || !Object.values(item.capabilities).every((value) => typeof value === 'boolean')) throw new Error(`Provider ${item.id} has invalid capabilities`);
    if (!item.eventMap || typeof item.eventMap !== 'object' || Array.isArray(item.eventMap) || typeof item.eventSource !== 'string') throw new Error(`Provider ${item.id} has no event mapping`);
    ids.add(item.id);
  }
  const loaded = new Set();
  function collect(module) {
    if (!module || loaded.has(module.filename)) return;
    if (!module.filename.startsWith(agentsRoot + path.sep)) return;
    loaded.add(module.filename);
    for (const child of module.children || []) collect(child);
  }
  collect(require.cache[registryFile]);
  const files = [...loaded].sort().map((file) => ({
    path: path.relative(sourceRoot, file).split(path.sep).join('/'),
    sha256: sha(fs.readFileSync(file)),
  }));
  // Hash names as well as bytes: file renames or added provider modules are
  // visible to --check even when their exported data happens to be identical.
  const source = { registry: 'agents/registry.js', sha256: sha(JSON.stringify(files)), files };
  return { version: 1, source, providers };
}

function catalogText(catalog) { return `${JSON.stringify(catalog, null, 2)}\n`; }
function labelsText(catalog) {
  const labels = catalog.providers.map(({ id, name }) => ({ id, name }));
  return `/* Generated by scripts/sync-provider-catalog.cjs; edit agents/registry.js sources. */\n(function(root,factory){'use strict';const api=factory();if(typeof module==='object'&&module.exports)module.exports=api;else root.OfficeProviders=api;})(typeof globalThis==='object'?globalThis:this,function(){'use strict';\nconst providers=Object.freeze(${JSON.stringify(labels)}.map(Object.freeze));\nconst aliases=Object.freeze({cursor:'cursor-agent',claude:'claude-code'});\nconst byId=new Map(providers.map(item=>[item.id,item]));\nfunction getProvider(id){return typeof id==='string'?byId.get(aliases[id]||id)||null:null;}\nreturn Object.freeze({getProvider,getAllProviders:()=>providers});\n});\n`;
}

function syncProviderCatalog({ registryRoot = DEFAULT_REGISTRY_ROOT, outputPath = DEFAULT_OUTPUT, labelsOutputPath = path.join(path.dirname(outputPath), 'provider-labels.js'), check = false } = {}) {
  const catalog = buildCatalog({ registryRoot });
  const artifacts = [{ file: outputPath, text: catalogText(catalog) }, { file: labelsOutputPath, text: labelsText(catalog) }];
  let changed = false;
  for (const artifact of artifacts) {
    let previous;
    try { previous = fs.readFileSync(artifact.file, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (previous === artifact.text) continue;
    changed = true;
    if (check) continue;
    fs.mkdirSync(path.dirname(artifact.file), { recursive: true });
    const temp = `${artifact.file}.${process.pid}.tmp`;
    try {
      fs.writeFileSync(temp, artifact.text, { flag: 'wx', mode: 0o644 });
      fs.renameSync(temp, artifact.file);
    } finally {
      try { fs.unlinkSync(temp); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    }
  }
  return { changed, count: catalog.providers.length, outputPath, labelsOutputPath, catalog };
}

if (require.main === module) {
  try {
    const args = process.argv.slice(2);
    if (args.some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/sync-provider-catalog.cjs [--check]');
    const check = args.includes('--check');
    const result = syncProviderCatalog({ check });
    process.stdout.write(`${check ? (result.changed ? 'Out of date' : 'In sync') : (result.changed ? 'Synced' : 'Unchanged')}: ${result.count} provider definitions\n`);
    if (check && result.changed) process.exitCode = 1;
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

module.exports = { buildCatalog, catalogText, labelsText, syncProviderCatalog };
